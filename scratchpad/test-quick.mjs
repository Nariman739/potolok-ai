// Быстрые ответы помощника: типовые вопросы не должны уходить в модель,
// а нетиповые — должны.
import { quickAnswer } from "../src/lib/assistant-quick.ts";
let ok = 0, fail = 0; const check = (n, c, x = "") => { if (c) { ok++; console.log("✅", n); } else { fail++; console.log("❌", n, x); } };

const hits = [
  "где посмотреть долги?", "как отправить в цех", "куда вписать деньги",
  "как сделать кп", "где мои цены", "как добавить монтажника",
  "как расставить софиты", "что значит этап согласовали", "как восстановить пароль",
];
for (const q of hits) check(`отвечаем сами: «${q}»`, !!quickAnswer(q, false), "ушло в модель");

const misses = [
  "зал 4 на 5 метров, посчитай",
  "клиент просит скидку 10 процентов что делать",
  "почему у меня не сходится площадь 18.5 и периметр 17",
  "как дела",
  "привет",
];
for (const q of misses) check(`отдаём модели: «${q}»`, !quickAnswer(q, false), "ответили шаблоном");
check("с фото всегда модель", !quickAnswer("как отправить в цех", true));


// Казахские вопросы тоже должны ловиться и отвечаться по-казахски
const kkCases = [["ақша қайда", "деньги"], ["цехқа қалай жіберемін", "цех"], ["өлшеуді қалай бастаймын", "замер"]];
for (const [q, rule] of kkCases) {
  const r = quickAnswer(q, false, "kk");
  check(`казахский вопрос «${q}»`, !!r && r.rule === rule && /[әғқңөұүһі]/i.test(r.answer), JSON.stringify(r)?.slice(0, 80));
}
console.log(`\n${ok} ok, ${fail} fail`); process.exit(fail ? 1 : 0);
