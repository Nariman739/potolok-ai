/**
 * Готовый ответ или null, если вопрос не типовой.
 * hasPhoto — в разговоре есть фото: тогда это работа с замером, не навигация.
 */
export function quickAnswer(
  message: string,
  hasPhoto: boolean,
  lang: "ru" | "kk" = "ru",
): { answer: string; rule: string } | null {
  if (hasPhoto) return null;
  const text = message.trim();
  if (text.length < 4 || text.length > 120) return null;
  // Цифры в вопросе почти всегда означают размеры комнаты — это к модели.
  if (/\d{2,}/.test(text)) return null;
  if (!ASKS.test(text)) return null;

  const hits = RULES.filter((r) => r.test.test(text));
  // Совпало сразу несколько тем — вопрос сложнее, чем кажется.
  if (hits.length !== 1) return null;
  const hit = hits[0];
  return { answer: (lang === "kk" && hit.kk) || hit.answer, rule: hit.name };
}
