/**
 * Единый рубильник монетизации.
 *
 * Пока сервис бесплатный для всех: подписку не продаём, доступ никому не режем.
 * Всё платное (гейт «оформите подписку», баннеры об окончании триала, страница
 * тарифов, промокоды) прячется за этим флагом — чтобы не путать мастеров,
 * которые пришли просто работать.
 *
 * Когда решим брать деньги — ставим BILLING_ENABLED=true в Vercel env, и вся
 * платная механика (она никуда не делась) включается обратно одним движением.
 * Перед этим не забыть проставить paidUntil тем, кому обещали бесплатный период.
 */
export const BILLING_ENABLED = process.env.BILLING_ENABLED === "true";

/**
 * То же самое для клиентских компонентов: в браузер попадают только
 * NEXT_PUBLIC_*-переменные, поэтому флага два. Держать их в одном значении —
 * в Vercel задаём обе (BILLING_ENABLED и NEXT_PUBLIC_BILLING_ENABLED).
 */
export const BILLING_ENABLED_CLIENT =
  process.env.NEXT_PUBLIC_BILLING_ENABLED === "true";
