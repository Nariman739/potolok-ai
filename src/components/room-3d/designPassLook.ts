  /** Все пункты ниже — только в «▶ Показать клиенту»: обычный вид мастера байт в байт
   *  (решение 08.11 — светлое полотно — не трогаем). false — пункты везде, где включены. */
  showOnly: true,
  /** Только для кадров было/стало (__DEV__): вид показа без автоповорота и плашек. */
  devForceShow: false,

  /** (1) «Показать клиенту»: экспозиция по свету. Обычный вид мастера не меняется
   *  (решение Наримана 08.11 — светлое полотно). */
