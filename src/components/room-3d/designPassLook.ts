// Главная находка этапа 1: «белое на белом» — на фото медиана яркости кадра
// 119–210 и ≥245 sRGB 0,2–8 % кадра, у нас 202–236 и до 17 %. Лента и линзы
// софитов toneMapped=false — экспозиция их не трогает, поэтому «экспозиция по
// свету» темнит полотно и стены, а свет остаётся светом.

