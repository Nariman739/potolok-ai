  showExposure: 0.8,
  /** Ровная подсветка полотна в запечке (ceilingBake CEILING_BASE 0.16 в обычном виде). */
  showCeilingBase: 0.08, // 0.04 — полотно в серое (кадры этапа 2, 11.11)
