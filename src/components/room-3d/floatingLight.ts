// Свет LED-ленты из щели — парящий потолок (этап 5, лист 03, 08.11.2026,
// выбор Наримана: вариант Б «мягче и меньше ватт»). Одно место на всё, что
// светит из щели: периметр парящего (Room3D.WallTopProfile) и — дальше — борт
// ступеньки двухуровневого потолка («2 уровня», type level2), где тот же
// профиль ложится на вертикальный борт и на нижний уровень полотна.
//
// По эталону парящий-3 / asr-1..3: тонкая светлая линия щели, верх стены
// 10–15 см заметно светлее, дальше ровный спад без резкой границы, к 40–50 см
// обычный тон стены; кромка полотна у щели +30 % на 8 см.
// Стены под парящим НЕ затемняются — это не вечерний режим.

/** Профиль засвета по расстоянию d (м) от щели, пик 1 (нормируется в текстуру);
 *  10 см ≈ 0.4, 30 см ≈ 0.14, 60 см ≈ 0.05, к 1 м — 0. */
export function floatingWash(d: number): number {
  return 0.75 * Math.exp(-d / 0.1) + 0.25 * Math.exp(-d / 0.35) * Math.max(0, 1 - d / FLOATING_WASH_H);
}

/** Сила засвета (opacity аддитивной плоскости): «меньше ватт» — 0.7 от прежнего 1.0. */
export const FLOATING_WASH_OPACITY = 0.7;

/** Высота плоскости засвета по стене, м (дальше профиль = 0). */
export const FLOATING_WASH_H = 1.0;

/** Высота светящейся щели, м (15 мм). */
export const FLOATING_CORE_H = 0.015;
/** Цвет щели: светлая, но не белая дыра (toneMapped=false, без клипа в #FFFFFF). */
export const FLOATING_CORE_HEX = "#F4F1EA";

/** Засвет кромки полотна у щели: пик (линейная доля) и ширина, м — в карту полотна. */
export const FLOATING_EDGE_K = 0.3;
export const FLOATING_EDGE_W = 0.08;
export function floatingEdge(t: number): number {
  return t < FLOATING_EDGE_W ? FLOATING_EDGE_K * Math.pow(1 - t / FLOATING_EDGE_W, 1.3) : 0;
}
