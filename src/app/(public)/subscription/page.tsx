function kzt(n: number) {
  return new Intl.NumberFormat("ru-RU").format(n) + " ₸";
}
function rub(n: number) {
  return new Intl.NumberFormat("ru-RU").format(n) + " ₽";
}

// «До 1 января» читается как «по 31 декабря включительно» — показываем последний день (как в /terms).
function fmtDate(d: Date) {
  return new Date(d.getTime() - 1).toLocaleDateString("ru-RU", { day: "numeric", month: "long", year: "numeric", timeZone: "Asia/Almaty" });
}

